-- ---------------------------------------------------------------------
-- 5.5: Function (get_compa_ratio)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION get_compa_ratio (
   p_employee_id IN NUMBER
) RETURN NUMBER AS
   v_ratio NUMBER;
BEGIN
   SELECT ROUND(e.salary / NULLIF((j.min_salary + j.max_salary) / 2, 0), 2)
   INTO v_ratio
   FROM employees e
   JOIN jobs j ON e.job_id = j.job_id
   WHERE e.employee_id = p_employee_id;
   
   RETURN v_ratio;
END get_compa_ratio;
/

