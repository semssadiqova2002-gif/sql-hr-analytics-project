-- ---------------------------------------------------------------------
-- 5.3: Audit Trigger
-- ---------------------------------------------------------------------
-- Audit loq cədvəlinin yaradılması[cite: 13]
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE perf_score_log PURGE';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE perf_score_log (
   log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   employee_id NUMBER,
   review_year NUMBER,
   old_score   NUMBER(2,1),
   new_score   NUMBER(2,1),
   changed_at  DATE,
   changed_by  VARCHAR2(50)
);

-- Triggerin yaradılması[cite: 13]
CREATE OR REPLACE TRIGGER trg_perf_score_audit
AFTER UPDATE OF perf_score ON perf_reviews
FOR EACH ROW
BEGIN
   IF :OLD.perf_score <> :NEW.perf_score THEN
      INSERT INTO perf_score_log (
         employee_id, review_year, old_score, new_score, changed_at, changed_by
      ) VALUES (
         :OLD.employee_id, :OLD.review_year, :OLD.perf_score, :NEW.perf_score, SYSDATE, USER
      );
   END IF;
END;
/


-- ---------------------------------------------------------------------
-- 5.4: Procedure (set_score)
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE set_score (
   p_employee_id IN NUMBER,
   p_year        IN NUMBER,
   p_score       IN NUMBER
) AS
BEGIN
   UPDATE perf_reviews
   SET perf_score = p_score,
       rating_label = CASE 
          WHEN p_score >= 4.0 THEN 'Exceeds'
          WHEN p_score BETWEEN 3.0 AND 3.9 THEN 'Meets'
          WHEN p_score < 3.0 THEN 'Below'
          ELSE rating_label
       END
   WHERE employee_id = p_employee_id 
     AND review_year = p_year 
     AND p_score BETWEEN 1 AND 5; -- Səhv bal (məs. 7) verilərsə dəyişiklik etmir[cite: 13]
   
   COMMIT;
END set_score;
/

